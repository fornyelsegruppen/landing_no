export const panelLocales = ["nb", "lt", "en"] as const;

export type PanelLocale = (typeof panelLocales)[number];

export function normalizePanelLocale(value: unknown): PanelLocale {
  return value === "lt" || value === "en" || value === "nb" ? value : "nb";
}

export function panelDateLocale(locale: PanelLocale) {
  return locale === "lt" ? "lt-LT" : locale === "en" ? "en-GB" : "nb-NO";
}

